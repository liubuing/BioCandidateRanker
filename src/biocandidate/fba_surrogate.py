"""Distill genome-scale FBA capability into the ranker architecture.

The fusion the user asked for: the original BioCandidateRanker model should
itself be able to answer the questions iML1515 and iJO1366 answer — given a
medium and a genetic scenario, what growth does the cell achieve? — without
invoking cobra at inference.

This module trains ranker checkpoints on simulation grids generated by
biocandidate.fba_context. The scenario (medium bounds, knockout flag,
overexpression factors, fusion caps) is encoded as the 8-wide fba_context
input; the FBA-computed biomass flux is the log10_flux label. Protein and
molecule modalities are disabled, exactly as in the governed simulated-flux
smoke, so the trained pathway is the fba_context one.

Claim boundary: the checkpoints are surrogates of simulations. They are not
experimental flux models, they do not replace the GEM outside the sampled
scenario distribution, and they make no scientific claim about real cells.
"""

