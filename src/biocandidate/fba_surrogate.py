def _scenario_vector(
    scenario: dict[str, Any],
    glucose: float,
    oxygen: float,
    target: str = "growth",
    model_id: str = "iML1515",
) -> tuple[float, ...]:
    """Encode one (scenario, target) pair as the model's 8-wide input vector.

    The vector is 8 wide for every model; what the slots mean is declared in
    SCENARIO_FEATURE_IDS_BY_MODEL, and the target selector is always last.
    """
    if target not in TARGET_SELECTORS:
        raise ValueError(f"unknown target {target!r}; known: {list(TARGET_SELECTORS)}")
    if target not in MODEL_TARGETS.get(model_id, ()):
        raise ValueError(f"target {target!r} is not declared for {model_id}")

    if model_id == "yeast_metatwin":
        return (
            float(glucose),
            float(oxygen),
            ROUTE_SELECTORS[scenario["route"]],
            1.0 if scenario.get("pox1_closed") else 0.0,
            OBJECTIVE_SELECTORS[scenario["objective"]],
            float(scenario.get("biomass_floor_fraction", 0.0)),
            0.0,  # spare
            TARGET_SELECTORS[target],
        )

    fusion = scenario.get("fusion") or {}
    return (
        float(glucose),
        float(oxygen),
        float(fusion.get("nog", 0.0)),
        float(fusion.get("phosphite", 0.0)),
        float(FUSION_CO2_CAP if fusion else 0.0),
        1.0 if scenario.get("ko") else 0.0,
        float(scenario["oe"][1]) if scenario.get("oe") else 0.0,
        TARGET_SELECTORS[target],
    )


FUSION_CO2_CAP = 5.0

# Royal jelly acid media grid. The yeast model file caps glucose uptake at 1.0,
# so the grid spans below and above that cap rather than the E. coli values.
YEAST_GLUCOSE_GRID = (0.25, 0.5, 1.0, 2.0, 3.0)
YEAST_OXYGEN_GRID = (250.0, 500.0, 750.0, 1000.0, 1500.0)
YEAST_ROUTES = ("A", "B")
YEAST_OBJECTIVES = ("growth", "target")
YEAST_BIOMASS_FLOOR_FRACTION = 0.1


def build_scenarios(model_id: str) -> list[dict[str, Any]]:
    """Enumerate the model's full grid: medium combos crossed with scenarios."""
    rows: list[dict[str, Any]] = []
    if model_id == "yeast_metatwin":
        for route, pox1_closed, objective in itertools.product(
            YEAST_ROUTES, (False, True), YEAST_OBJECTIVES
        ):
            for glucose in YEAST_GLUCOSE_GRID:
                for oxygen in YEAST_OXYGEN_GRID:
                    scenario = {
                        "name": f"route{route}_{'pox1_off' if pox1_closed else 'pox1_on'}_{objective}",
                        "route": route,
                        "pox1_closed": pox1_closed,
                        "objective": objective,
                        "biomass_floor_fraction": (
                            YEAST_BIOMASS_FLOOR_FRACTION if objective == "target" else 0.0
                        ),
                    }
                    rows.append(
                        {
                            "model_id": model_id,
                            "scenario": scenario,
                            "glucose": glucose,
                            "oxygen": oxygen,
                        }
                    )
        return rows

    scenarios = IML1515_SCENARIOS if model_id == "iML1515" else IJO1366_SCENARIOS
    for scenario in scenarios:
        for glucose in GLUCOSE_GRID:
            for oxygen in OXYGEN_GRID:
                rows.append(
                    {
                        "model_id": model_id,
                        "scenario": scenario,
                        "glucose": glucose,
                        "oxygen": oxygen,
                    }
                )
    return rows


def _condition_hash(model_id: str, scenario: dict[str, Any], glucose: float, oxygen: float) -> str:
    scenario_name = scenario.get("name", scenario.get("route", "baseline"))
    payload = json.dumps(
        {"model": model_id, "scenario": scenario_name, "glucose": glucose, "oxygen": oxygen},
        sort_keys=True,
    ).encode("utf-8")
    return "sha256:" + hashlib.sha256(payload).hexdigest()


def run_fba_grid(
    model_id: str,
    *,
    model=None,
    model_sha256: str | None = None,
) -> dict[str, Any]:
    """Solve every scenario in the grid on ONE model copy.

    Bound changes are reverted between scenarios, so a single copy serves the
    whole sweep; each returned row carries the objective flux plus the scenario
    identity needed for training records.
    """
    if model_id not in MODEL_REGISTRY:
        raise ValueError(f"unknown model {model_id!r}; known: {sorted(MODEL_REGISTRY)}")
    from .fba_context import CORE_COFACTORS, add_fusion_pathways, cofactor_turnover

    spec = MODEL_REGISTRY[model_id]
    if model_id == "yeast_metatwin":
        return _run_yeast_grid(model=model, model_sha256=model_sha256)

    base = model if model is not None else load_model(model_id)
    scoped = base.copy()
    scoped.objective = spec["objective_id"]

    use_fusion = any(row["scenario"].get("fusion") for row in build_scenarios(model_id))
    if use_fusion:
        add_fusion_pathways(scoped)

    rows: list[dict[str, Any]] = []
    dropped: list[dict[str, Any]] = []
    for row in build_scenarios(model_id):
        scenario = row["scenario"]
        glucose, oxygen = row["glucose"], row["oxygen"]

        with scoped:
            scoped.reactions.get_by_id(GLUCOSE_EXCHANGE).lower_bound = -float(glucose)
            scoped.reactions.get_by_id(OXYGEN_EXCHANGE).lower_bound = -float(oxygen)
            if scenario.get("fusion"):
                caps = scenario["fusion"]
                scoped.reactions.EX_co2_e.lower_bound = -FUSION_CO2_CAP
                scoped.reactions.NOG_F6P.upper_bound = float(caps["nog"])
                scoped.reactions.EX_phite_e.lower_bound = -float(caps["phosphite"])
                if caps["phosphite"] == 0:
                    scoped.reactions.PTXD.upper_bound = 0.0

            ko_targets = []
            if scenario.get("ko"):
                gene = next(g for g in scoped.genes if g.name == "ptsG" or g.id == "ptsG")
                for reaction in gene.reactions:
                    ko_targets.append((reaction, reaction.lower_bound, reaction.upper_bound))
                    reaction.bounds = (0.0, 0.0)
            oe_target = None
            if scenario.get("oe"):
                rid, factor = scenario["oe"]
                reaction = scoped.reactions.get_by_id(rid)
                baseline = scoped.optimize()
                optimum = float(baseline.fluxes[rid]) if baseline.status == "optimal" else 0.0
                if optimum > 0:
                    oe_target = (reaction, reaction.lower_bound)
                    reaction.lower_bound = factor * optimum

            solution = scoped.optimize()

            for reaction, lb, ub in ko_targets:
                reaction.bounds = (lb, ub)
            if oe_target:
                oe_target[0].lower_bound = oe_target[1]

        targets: dict[str, float] = {}
        if solution.status == "optimal":
            growth = float(solution.objective_value)
            if growth > 1e-9:
                targets["growth"] = growth
            # only the core trio: the surrogate contract is fixed at these three
            # plus growth, and scanning all declared cofactors per scenario would
            # multiply the grid cost for targets nothing consumes
            turnover = cofactor_turnover(
                scoped,
                solution,
                {label: spec["cofactor_metabolites"][label] for label in CORE_COFACTORS},
            )
            for label in CORE_COFACTORS:
                info = turnover.get(label, {})
                value = info.get("gross_turnover")
                if info.get("status") == "reported" and value and value > 1e-9:
                    targets[label] = float(value)
        if not targets:
            dropped.append({"scenario": scenario["name"], "glucose": glucose, "oxygen": oxygen})
            continue

        scenario_id = _condition_hash(model_id, scenario, glucose, oxygen)
        scenario_name = scenario.get("name", scenario.get("route", "baseline"))
        for target, value in targets.items():
            rows.append(
                {
                    "model_id": model_id,
                    "scenario_name": scenario_name,
                    "glucose": glucose,
                    "oxygen": oxygen,
                    "target": target,
                    "features": list(
                        _scenario_vector(scenario, glucose, oxygen, target, model_id)
                    ),
                    "log10_flux": math.log10(value),
                    "value": value,
                    "condition_id": f"{scenario_id}#{target}",
                    "scenario_id": scenario_id,
                }
            )

    return {
        "model_id": model_id,
        "rows": rows,
        "dropped": dropped,
        "feature_ids": list(SCENARIO_FEATURE_IDS_BY_MODEL[model_id]),
        "objective_id": spec["objective_id"],
        "model_sha256": model_sha256,
        "claim_boundary": SURROGATE_CLAIM_BOUNDARY,
        "fba_claim_boundary": FBA_CLAIM_BOUNDARY,
    }


def _run_yeast_grid(
    *, model=None, model_sha256: str | None = None
) -> dict[str, Any]:
    """Solve the royal-jelly-acid scenario grid on the yeast model.

    Every scenario shares one extended model copy. Per scenario the medium, the
    route (the other one is blocked so each capacity is that route's own), the
    POX1 choice and the objective are applied, then the targets are read at the
    resulting optimum: growth, the target demand flux, and the cofactor
    turnovers. Infeasible combinations are dropped and reported rather than
    guessed at.
    """
    from .fba_context import cofactor_turnover
    from .royal_jelly_acid import (
        BIOMASS_ID,
        POX1_REACTION,
        ROUTE_A,
        ROUTE_B,
        TARGET_DEMAND,
        build_candidate_extension,
        load_target_config,
    )

    spec = MODEL_REGISTRY["yeast_metatwin"]
    base = model if model is not None else load_model("yeast_metatwin")
    scoped = base.copy()
    build_candidate_extension(scoped, load_target_config(YEAST_TARGET_CONFIG))

    routes = {"A": ROUTE_A, "B": ROUTE_B}
    cofactor_ids = {
        label: spec["cofactor_metabolites"][label]
        for label in ("nadph", "nadh", "atp", "accoa")
    }

    rows: list[dict[str, Any]] = []
    dropped: list[dict[str, Any]] = []
    for row in build_scenarios("yeast_metatwin"):
        scenario = row["scenario"]
        glucose, oxygen = row["glucose"], row["oxygen"]
        scenario_name = scenario["name"]

        with scoped:
            scoped.reactions.get_by_id("r_1714").lower_bound = -float(glucose)
            scoped.reactions.get_by_id("r_1992").lower_bound = -float(oxygen)
            if scenario["pox1_closed"]:
                scoped.reactions.get_by_id(POX1_REACTION).bounds = (0.0, 0.0)
            for other, reaction_ids in routes.items():
                if other == scenario["route"]:
                    continue
                for reaction_id in reaction_ids:
                    scoped.reactions.get_by_id(reaction_id).bounds = (0.0, 0.0)

            growth_max = float(scoped.slim_optimize())
            if growth_max <= 0:
                dropped.append({"scenario": scenario_name, "glucose": glucose,
                                "oxygen": oxygen, "reason": "no growth"})
                continue

            if scenario["objective"] == "growth":
                scoped.objective = BIOMASS_ID
            else:
                scoped.reactions.get_by_id(BIOMASS_ID).lower_bound = (
                    growth_max * scenario["biomass_floor_fraction"]
                )
                scoped.objective = TARGET_DEMAND

            solution = scoped.optimize()
            if solution.status != "optimal":
                dropped.append({"scenario": scenario_name, "glucose": glucose,
                                "oxygen": oxygen, "reason": solution.status})
                continue

            values: dict[str, float] = {
                "growth": float(solution.fluxes[BIOMASS_ID]),
                "capacity": float(solution.fluxes[TARGET_DEMAND]),
            }
            turnover = cofactor_turnover(scoped, solution, cofactor_ids)
            for label in ("nadph", "nadh", "atp", "accoa"):
                info = turnover.get(label, {})
                value = info.get("gross_turnover")
                if info.get("status") == "reported" and value is not None:
                    values[label] = float(value)

        usable = {k: v for k, v in values.items() if v > 1e-9}
        if "growth" not in usable:
            dropped.append({"scenario": scenario_name, "glucose": glucose,
                            "oxygen": oxygen, "reason": "no measurable growth"})
            continue

        scenario_id = _condition_hash("yeast_metatwin", scenario, glucose, oxygen)
        for target, value in usable.items():
            rows.append(
                {
                    "model_id": "yeast_metatwin",
                    "scenario_name": scenario_name,
                    "glucose": glucose,
                    "oxygen": oxygen,
                    "target": target,
                    "features": list(
                        _scenario_vector(scenario, glucose, oxygen, target, "yeast_metatwin")
                    ),
                    "log10_flux": math.log10(value),
                    "value": value,
                    "condition_id": f"{scenario_id}#{target}",
                    "scenario_id": scenario_id,
                }
            )

    return {
        "model_id": "yeast_metatwin",
        "rows": rows,
        "dropped": dropped,
        "feature_ids": list(SCENARIO_FEATURE_IDS_BY_MODEL["yeast_metatwin"]),
        "objective_id": spec["objective_id"],
        "model_sha256": model_sha256,
        "target_config": str(YEAST_TARGET_CONFIG),
        "claim_boundary": SURROGATE_CLAIM_BOUNDARY,
        "fba_claim_boundary": FBA_CLAIM_BOUNDARY,
    }


def _record(row: dict[str, Any], fba_payload: dict[str, Any], source_row: int) -> EnzymeSubstrateRecord:
    return EnzymeSubstrateRecord(
        sequence="X",
        substrate_smiles="O",
        organism="Escherichia coli (model context only)",
        ec="not_applicable",
        enzyme_type="simulated_fba_condition",
        candidate_id=row["condition_id"],
        reaction=fba_payload["objective_id"],
        fba_context=tuple(row["features"]),
        fba_feature_metadata=FBAFeatureMetadata(
            schema_version=1,
            feature_ids=tuple(fba_payload["feature_ids"]),
            model_id=row["model_id"],
            solver_id="glpk",
            objective_id=fba_payload["objective_id"],
            condition_id=row["condition_id"],
        ),
        log10_flux=row["log10_flux"],
        flux_label_metadata=FluxLabelMetadata(
            label_type=FluxLabelType.SIMULATED,
            # Growth names the biomass objective; the cofactor targets name a
            # turnover quantity, which the metadata contract permits since
            # target_reaction_id is any non-empty identifier and the canonical
            # unit is the same mmol gDW^-1 h^-1 in both cases.
            target_reaction_id=(
                fba_payload["objective_id"]
                if row["target"] == "growth"
                else TARGET_REACTION_IDS[row["target"]]
            ),
            canonical_unit=CANONICAL_LOG10_FLUX_UNIT,
            provenance_json=json.dumps(
                {
                    "scenario": row["scenario_name"],
                    "target": row["target"],
                    "glucose": row["glucose"],
                    "oxygen": row["oxygen"],
                    "model_sha256": fba_payload.get("model_sha256"),
                },
                sort_keys=True,
            ),
        ),
        source_dataset=f"{SOURCE_DATASET}-{row['model_id']}",
        source_row=source_row,
        split=row["split"],
    )


def assign_splits(rows: list[dict[str, Any]]) -> None:
    """Deterministic ~72/14/14 split, taken over SCENARIOS rather than rows.

    A scenario contributes one row per target, and those rows share the same
    scenario vector apart from the selector slot. Splitting rows independently
    would put, say, the growth row of a scenario in train and its NADPH row in
    test, which leaks the scenario across the split boundary. The unit of
    assignment is therefore the scenario id, and every target inherits it.

    The hash sort pseudo-randomizes the order, so proportional slices of the
    sorted list are random samples; max(1, n//7) per minor partition keeps
    validation and test non-empty even on miniature grids.
    """
    scenario_ids = sorted({row["scenario_id"] for row in rows})
    n_val = max(1, len(scenario_ids) // 7)
    n_test = max(1, len(scenario_ids) // 7)
    assignment: dict[str, str] = {}
    for index, scenario_id in enumerate(scenario_ids):
        if index < n_val:
            assignment[scenario_id] = "validation"
        elif index < n_val + n_test:
            assignment[scenario_id] = "test"
        else:
            assignment[scenario_id] = "train"
    for row in rows:
        row["split"] = assignment[row["scenario_id"]]


def _per_target_metrics(
    model,
    loaders: dict[str, Any],
    device,
    partitions: dict[str, list[EnzymeSubstrateRecord]],
    train_rows: list[dict[str, Any]],
    test_rows: list[dict[str, Any]],
) -> dict[str, Any]:
    """Test-set RMSE per target, each against its own train-mean baseline.

    Predictions are made through the ordinary validation loader; rows are
    matched back to their target through the provenance the record carries.
    """
    import torch

    report: dict[str, Any] = {}
    for row in test_rows:
        report.setdefault(row["target"], {"count": 0, "squared_error": 0.0})
    if not report:
        return {}

    loader = loaders["test"]
    records = partitions["test"]
    with torch.no_grad():
        index = 0
        for batch in loader:
            batch = {name: value.to(device) for name, value in batch.items()}
            output = model(batch)
            means = output["mean"][:, 0].detach().cpu().tolist()
            labels = batch["labels"][:, 0].detach().cpu().tolist()
            for mean, label in zip(means, labels):
                record = records[index]
                target = json.loads(record.flux_label_metadata.provenance_json)["target"]
                entry = report[target]
                entry["count"] += 1
                entry["squared_error"] += (mean - label) ** 2
                index += 1

    for target, entry in report.items():
        train_labels = [row["log10_flux"] for row in train_rows if row["target"] == target]
        test_labels = [row["log10_flux"] for row in test_rows if row["target"] == target]
        baseline = float("nan")
        if train_labels and test_labels:
            mean_label = sum(train_labels) / len(train_labels)
            baseline = math.sqrt(
                sum((value - mean_label) ** 2 for value in test_labels) / len(test_labels)
            )
        entry["test_rmse_log10"] = math.sqrt(entry.pop("squared_error") / entry["count"])
        entry["test_mean_baseline_rmse_log10"] = baseline
        if baseline == baseline and entry["test_rmse_log10"] > 0:
            entry["improvement_factor"] = baseline / entry["test_rmse_log10"]
    return report


def _pooled_baseline_rmse(
    train_rows: list[dict[str, Any]], test_rows: list[dict[str, Any]]
) -> float:
    """RMSE of predicting each target with its own train-set mean."""
    if not test_rows:
        return float("nan")
    total = 0.0
    for row in test_rows:
        train_labels = [
            other["log10_flux"] for other in train_rows if other["target"] == row["target"]
        ]
        mean_label = sum(train_labels) / len(train_labels) if train_labels else 0.0
        total += (row["log10_flux"] - mean_label) ** 2
    return math.sqrt(total / len(test_rows))


def train_surrogate(
    model_id: str,
    output_dir: str | Path,
    *,
    epochs: int = 120,
    seed: int = 7,
) -> dict[str, Any]:
    """Generate the grid, train a context-only ranker, evaluate, and freeze it."""
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    config_file = load_model_config(model_id)

    grid = run_fba_grid(model_id, model_sha256=config_file["sha256"])
    assign_splits(grid["rows"])
    dataset_path = output / "simulated_flux.jsonl"
    with dataset_path.open("w", encoding="utf-8") as handle:
        for row in grid["rows"]:
            handle.write(json.dumps(row, sort_keys=True) + "\n")

    records = [
        _record(row, grid, index)
        for index, row in enumerate(grid["rows"])
    ]
    partitions = {
        name: [record for record in records if record.split == name]
        for name in SPLITS
    }
    if any(not values for values in partitions.values()):
        raise RuntimeError("surrogate split contains an empty partition")

    torch.manual_seed(seed)
    random.seed(seed)
    config = ModelConfig(
        d_model=24,
        num_heads=2,
        protein_layers=1,
        molecule_layers=1,
        fusion_layers=1,
        protein_chunk_size=8,
        context_buckets=64,
        fba_context_dim=len(SCENARIO_FEATURE_IDS),
        dropout=0.0,
        use_protein=False,
        use_molecule=False,
        use_context=True,
        uncertainty_mode="fixed_variance_mse",
        task_names=("log10_flux",),
    )
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = BioCandidateRanker(config).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=2e-3)
    collator = EnzymeSubstrateCollator(
        context_buckets=config.context_buckets,
        fba_context_dim=config.fba_context_dim,
        task_names=config.task_names,
    )
    loaders = {
        name: DataLoader(
            RecordDataset(values), batch_size=16, shuffle=(name == "train"),
            collate_fn=collator,
        )
        for name, values in partitions.items()
    }

    best_validation = float("inf")
    best_state = None
    best_epoch = 0
    for epoch in range(1, epochs + 1):
        run_epoch(model, loaders["train"], device, optimizer)
        validation = run_epoch(model, loaders["validation"], device)
        if validation.loss < best_validation:
            best_validation = validation.loss
            best_epoch = epoch
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
    if best_state is not None:
        model.load_state_dict(best_state)

    train_metrics = run_epoch(model, loaders["train"], device)
    validation_metrics = run_epoch(model, loaders["validation"], device)
    test_metrics = run_epoch(model, loaders["test"], device)

    # Per-target scoring, because the pooled loss mixes quantities whose spread
    # differs by an order of magnitude: growth sits near 1 mmol gDW-1 h-1 while
    # ATP turnover is around 70, so a single pooled RMSE would be dominated by
    # the largest-flux target and would hide a bad growth fit.
    train_rows = [row for row in grid["rows"] if row["split"] == "train"]
    test_rows = [row for row in grid["rows"] if row["split"] == "test"]
    per_target = _per_target_metrics(model, loaders, device, partitions, train_rows, test_rows)

    metrics = {
        "status": "surrogate_trained",
        "model_id": model_id,
        "objective_id": grid["objective_id"],
        "device": str(device),
        "epochs": epochs,
        "best_epoch": best_epoch,
        "seed": seed,
        "task": "log10_flux",
        "targets": list(TARGETS),
        "target_selectors": dict(TARGET_SELECTORS),
        "validation_tasks": {
            "log10_flux": {
                "count": len(partitions["validation"]),
                "rmse": math.sqrt(validation_metrics.loss),
            }
        },
        "feature_ids": grid["feature_ids"],
        "rows": {name: len(values) for name, values in partitions.items()},
        "scenarios": {
            "train": len({row["scenario_id"] for row in train_rows}),
            "test": len({row["scenario_id"] for row in test_rows}),
        },
        "dropped_scenarios": len(grid["dropped"]),
        "train_rmse_log10": math.sqrt(train_metrics.loss),
        "validation_rmse_log10": math.sqrt(validation_metrics.loss),
        "test_rmse_log10": math.sqrt(test_metrics.loss),
        "per_target": per_target,
        # Pooled figure kept alongside the breakdown: it is the single number a
        # summary table can quote, while per_target is what tells you which
        # quantity is actually well modelled.
        "test_pooled_mean_baseline_rmse_log10": _pooled_baseline_rmse(train_rows, test_rows),
        "claim_boundary": SURROGATE_CLAIM_BOUNDARY,
    }
    save_checkpoint(
        output / "best.pt",
        model,
        optimizer,
        epoch=best_epoch,
        data_manifest={
            "surrogate_of": model_id,
            "model_sha256": config_file["sha256"],
            "dataset_rows": metrics["rows"],
            "dropped_scenarios": grid["dropped"],
            "feature_ids": grid["feature_ids"],
            "claim_boundary": SURROGATE_CLAIM_BOUNDARY,
            "fba_claim_boundary": FBA_CLAIM_BOUNDARY,
        },
        metrics=metrics,
    )
    (output / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    return metrics


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-id", default="iML1515", choices=sorted(MODEL_REGISTRY))
    parser.add_argument("--output-dir", default=None)
    # 900 is the yeast default because its scenario space mixes binary regime
    # switches with continuous media axes: 250 epochs does not converge and
    # yields a surrogate that fails to beat the mean baseline on half its
    # targets. The E. coli grids converge well inside 250.
    parser.add_argument("--epochs", type=int, default=900)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()

    output_dir = args.output_dir or f"artifacts/fba-surrogate-{args.model_id}"
    metrics = train_surrogate(args.model_id, output_dir, epochs=args.epochs, seed=args.seed)
    print(json.dumps(metrics, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


